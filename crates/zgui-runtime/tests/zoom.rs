//! That a window's zoom multiplies the platform scale everywhere CSS pixels meet device pixels.

mod support;

use std::cell::Cell;
use std::rc::Rc;
use std::time::Duration;

use zgui_geom::{Css, CssPx, Device, DevicePx, Point, Rect, Size};
use zgui_platform::SurfaceEvent;
use zgui_platform_headless::Harness;
use zgui_reactive::prelude::GetUntracked;
use zgui_runtime::{App, Runtime, Window, Zoom};
use zgui_view::{Anchor, BuildCx, IntoView, View};
use zgui_vocab::{
    KeyCode, KeyEvent, KeyState, Modifiers, NamedKey, PhysicalKey, PointerAction, PointerEvent,
    Timestamp,
};

/// A root as large as the window, a box of a fixed size, and a box whose width a media query sets.
const CSS: &str = "root { display: block; width: 100%; height: 100% }
                   .fixed { display: block; width: 100px; height: 10px }
                   .probe { display: block; width: 10px; height: 10px }
                   @media (max-width: 300px) { .probe { width: 20px } }";

/// A document whose one control is 40 by 20 CSS pixels at 50, 30.
const CONTROL_CSS: &str = "root { display: block; width: 100%; height: 100% }
                           control { display: block; width: 40px; height: 20px;
                                     margin: 30px 0 0 50px }";

/// A zoom of `factor`, which the caller knows to be in range.
fn zoom(factor: f32) -> Zoom {
    Zoom::new(factor).expect("the factor is in range")
}

/// An application of 400 by 300 CSS pixels at `zoom`, holding `view` and styled by `css`.
fn app<V>(css: &str, zoom: Zoom, view: V) -> Harness<Runtime>
where
    V: FnMut(&mut BuildCx<'_>) -> Box<dyn Anchor> + 'static,
{
    let handler = App::new()
        .with_title("test")
        .with_size(400.0, 300.0)
        .with_stylesheet(css)
        .with_zoom(zoom)
        .with_renderer(Box::new(support::capture))
        .into_handler(view)
        .expect("the reactive runtime installs");
    Harness::new(handler)
}

/// The fixture of [`CSS`].
fn boxes(cx: &mut BuildCx<'_>) -> Box<dyn Anchor> {
    Box::new(
        zgui_elements::column()
            .class("root")
            .child(zgui_elements::column().class("fixed"))
            .child(zgui_elements::column().class("probe"))
            .into_view()
            .build(cx),
    )
}

/// The border box of the first fragment of the first box generated by an element in `class`.
///
/// # Panics
///
/// Panics when no element carries the class.
fn class_box(window: &Window, class: &str) -> Rect<DevicePx, Device> {
    let layout = window.layout().borrow();
    let document = window.document().borrow();
    for key in layout.keys() {
        let Some(source) = layout.get(key).and_then(|node| node.source) else {
            continue;
        };
        let Some(index) = document.store().index_of(source) else {
            continue;
        };
        if !document
            .store()
            .classes_of(index)
            .iter()
            .any(|name| name.as_ref() == class)
        {
            continue;
        }
        let Some(fragment) = layout.fragments_of_box(key).first().copied() else {
            continue;
        };
        if let Some(fragment) = layout.fragment(fragment) {
            return fragment.on_device(fragment.border_box, &window.placements());
        }
    }
    panic!("no element carrying {class:?} produced a fragment");
}

/// One pointer event at `at`, in the platform's CSS pixels.
fn pointer(action: PointerAction, at: Point<CssPx, Css>) -> SurfaceEvent {
    SurfaceEvent::Pointer {
        action,
        event: PointerEvent::mouse(at),
        modifiers: Modifiers::NONE,
        timestamp: Timestamp::ORIGIN,
    }
}

/// Moves to `at`, presses and releases.
fn click(harness: &mut Harness<Runtime>, at: Point<CssPx, Css>) {
    harness.deliver_to_first(pointer(PointerAction::Moved, at));
    harness.deliver_to_first(pointer(PointerAction::Pressed, at));
    harness.deliver_to_first(pointer(PointerAction::Released, at));
    harness.settle(16);
}

#[test]
fn a_css_length_is_the_zoom_times_larger_on_the_device() {
    let mut harness = app(CSS, zoom(1.5), boxes);
    harness.settle(16);

    let window = &harness.app().windows()[0];
    assert_eq!(class_box(window, "fixed").size.width, DevicePx(150.0));
    assert_eq!(window.scale().get(), 1.5);

    harness.shut_down();
}

#[test]
fn the_css_viewport_is_the_surface_over_the_scale_and_the_zoom() {
    let mut harness = app(CSS, zoom(1.5), boxes);
    harness.deliver_to_first(SurfaceEvent::ScaleFactorChanged {
        scale_factor: 2.0,
        size: Size::new(DevicePx(800.0), DevicePx(600.0)),
    });
    harness.settle(16);

    let window = &harness.app().windows()[0];
    let handle = window.handle();
    assert_eq!(
        handle.size().get_untracked(),
        Size::new(CssPx(800.0 / 3.0), CssPx(600.0 / 3.0))
    );
    assert_eq!(handle.scale().get_untracked(), 2.0);
    assert_eq!(handle.zoom().get_untracked(), zoom(1.5));

    // The viewport is 266.7 CSS pixels wide, so `max-width: 300px` matches. At zoom 1 it is 400
    // wide and does not.
    assert_eq!(class_box(window, "probe").size.width, DevicePx(60.0));
    assert_eq!(class_box(window, "root").size.width, DevicePx(800.0));

    harness.shut_down();
}

#[test]
fn a_pointer_reaches_the_element_under_it_at_a_zoom() {
    let clicks = Rc::new(Cell::new(0_u32));
    let counted = Rc::clone(&clicks);
    let mut harness = app(CONTROL_CSS, zoom(2.0), move |cx: &mut BuildCx<'_>| {
        let counted = Rc::clone(&counted);
        Box::new(
            zgui_elements::column()
                .class("root")
                .child(
                    zgui_elements::control().on(zgui_view::events::CLICK, move |_| {
                        counted.set(counted.get() + 1);
                    }),
                )
                .into_view()
                .build(cx),
        )
    });
    harness.settle(16);

    // At zoom 2 the control covers 100 to 180 by 60 to 100 device pixels, and the platform scale
    // is 1. The platform reports the pointer in its own CSS pixels, which are device pixels here.
    click(&mut harness, Point::new(CssPx(140.0), CssPx(80.0)));
    assert_eq!(
        clicks.get(),
        1,
        "a click at the control's centre reached it"
    );

    // The control's own CSS coordinates, which are outside it on the device at zoom 2.
    click(&mut harness, Point::new(CssPx(70.0), CssPx(40.0)));
    assert_eq!(
        clicks.get(),
        1,
        "a click left of the control on the device reached it"
    );

    harness.shut_down();
}

#[test]
fn a_zoom_change_lays_the_document_out_again() {
    let mut harness = app(CSS, Zoom::ONE, boxes);
    harness.settle(16);
    {
        let window = &harness.app().windows()[0];
        assert_eq!(class_box(window, "fixed").size.width, DevicePx(100.0));
        assert_eq!(class_box(window, "probe").size.width, DevicePx(10.0));
    }

    let handle = harness.app().windows()[0].handle().clone();
    // Past the resize pacing interval, so the zoom is answered with a frame where it arrives.
    harness.advance(Duration::from_millis(25));
    handle.set_zoom(zoom(2.0));
    // The zoom and the size change together, when the window applies the zoom.
    assert_eq!(handle.zoom().get_untracked(), Zoom::ONE);
    assert_eq!(
        handle.size().get_untracked(),
        Size::new(CssPx(400.0), CssPx(300.0))
    );
    harness.settle(16);

    let window = &harness.app().windows()[0];
    assert_eq!(window.zoom(), zoom(2.0));
    assert_eq!(window.scale().get(), 2.0);
    assert_eq!(class_box(window, "fixed").size.width, DevicePx(200.0));
    // The viewport is 200 CSS pixels wide, so the media query matches.
    assert_eq!(class_box(window, "probe").size.width, DevicePx(40.0));
    assert_eq!(handle.zoom().get_untracked(), zoom(2.0));
    assert_eq!(
        handle.size().get_untracked(),
        Size::new(CssPx(200.0), CssPx(150.0))
    );
    assert_eq!(
        handle.scale().get_untracked(),
        1.0,
        "the platform scale does not include the zoom"
    );

    harness.shut_down();
}

/// The text element's border box on a surface of 400 by 300 device pixels at `scale` and `zoom`.
fn measured_at(scale: f64, zoom: Zoom) -> Rect<DevicePx, Device> {
    let mut harness = support::app_with_text(
        "root { display: flex } .measured { padding: 4px 6px }",
        |cx: &mut BuildCx<'_>| {
            Box::new(
                zgui_elements::row()
                    .class("root")
                    .child(zgui_elements::text().class("measured").child("abcdefgh"))
                    .into_view()
                    .build(cx),
            )
        },
    );
    harness.settle(16);
    harness.advance(Duration::from_millis(25));
    harness.deliver_to_first(SurfaceEvent::ScaleFactorChanged {
        scale_factor: scale,
        size: Size::new(DevicePx(400.0), DevicePx(300.0)),
    });
    harness.settle(16);
    harness.advance(Duration::from_millis(25));
    harness.app().windows()[0].handle().set_zoom(zoom);
    harness.settle(16);

    let box_ = class_box(&harness.app().windows()[0], "measured");
    harness.shut_down();
    box_
}

#[test]
fn text_under_a_zoom_is_measured_as_at_the_same_device_scale() {
    assert_eq!(measured_at(1.0, zoom(2.0)), measured_at(2.0, Zoom::ONE));
}

#[test]
fn an_input_method_is_told_the_caret_in_the_platforms_pixels() {
    let mut harness = support::app_with_text(
        "root { display: block; width: 400px; height: 300px }
         editor { display: block; width: 100px; height: 40px; margin: 30px 0 0 50px }",
        |cx: &mut BuildCx<'_>| {
            Box::new(
                zgui_elements::column()
                    .class("root")
                    .child(zgui_elements::editor().child("ab"))
                    .into_view()
                    .build(cx),
            )
        },
    );
    harness.settle(8);
    harness.advance(Duration::from_millis(25));
    harness.app().windows()[0].handle().set_zoom(zoom(2.0));
    harness.settle(8);
    harness.deliver_to_first(SurfaceEvent::Key {
        state: KeyState::Pressed,
        event: KeyEvent::named(NamedKey::Tab, PhysicalKey::Code(KeyCode::Tab)),
        modifiers: Modifiers::NONE,
        timestamp: Timestamp::ORIGIN,
    });
    harness.settle(8);

    let told = harness.platform().offscreens()[0]
        .last_text_input()
        .expect("the surface was told about text input")
        .expect("focusing an editor enables text input");
    // The field is at 50, 30 in the document's CSS pixels, which is 100, 60 on a platform with
    // scale 1 at zoom 2.
    assert_eq!(
        (told.caret_origin.x.0, told.caret_origin.y.0),
        (100.0, 60.0)
    );

    harness.shut_down();
}
